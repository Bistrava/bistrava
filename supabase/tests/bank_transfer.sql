begin;
do $$
declare
  bank jsonb:='{"beneficiary":"EXAMPLE TEST ONLY","iban":"GB82WEST12345698765432","bankName":"Example bank","bic":"DEUTDEFF","currency":"EUR"}';
  cart jsonb:='[{"sku":"TEST-01","quantity":1}]';
  rate uuid:='20000000-0000-4000-8000-000000000001';
  customer jsonb:='{"firstName":"Test","lastName":"Only"}'; address jsonb:='{"countryCode":"SI","postalCode":"1000","city":"Ljubljana","addressLine1":"Test only"}';
  key uuid:=gen_random_uuid(); first_order record; duplicate record; other record; quote jsonb; before_stock integer; admin_id uuid; rejected boolean; version timestamptz;
begin
  select profile_id into admin_id from public.admin_roles where active and role='admin' limit 1;
  select stock_quantity into before_stock from public.products where sku='TEST-01';
  quote:=public.quote_guest_checkout(cart,rate,null);
  rejected:=false;
  begin perform public.create_bank_transfer_order(cart,'test@example.test','123456789',customer,address,rate,'',repeat('e',64),key,null,(quote->>'totalCents')::integer,bank||'{"iban":"GB83WEST12345698765432"}'::jsonb);
  exception when others then if sqlerrm='bank_transfer_not_configured' then rejected:=true; else raise; end if; end;
  if not rejected then raise exception 'TEST invalid bank accepted'; end if;
  execute 'set local role authenticated';
  rejected:=false;
  begin perform public.create_bank_transfer_order(cart,'test@example.test','123456789',customer,address,rate,'',repeat('e',64),key,null,(quote->>'totalCents')::integer,bank);
  exception when insufficient_privilege then rejected:=true; end;
  if not rejected then raise exception 'TEST browser may create payment instructions'; end if;
  execute 'reset role';
  execute 'set local role service_role';
  select * into first_order from public.create_bank_transfer_order(cart,'test@example.test','123456789',customer,address,rate,'',repeat('e',64),key,null,(quote->>'totalCents')::integer,bank);
  select * into duplicate from public.create_bank_transfer_order(cart,'test@example.test','123456789',customer,address,rate,'',repeat('e',64),key,null,(quote->>'totalCents')::integer,bank||'{"beneficiary":"CHANGED CONFIG"}'::jsonb);
  if first_order.order_id<>duplicate.order_id then raise exception 'TEST idempotent bank order'; end if;
  execute 'reset role';
  if (select stock_quantity from public.products where sku='TEST-01')<>before_stock-1 then raise exception 'TEST duplicate reservation'; end if;
  if not exists(select 1 from public.orders where id=first_order.order_id and status='awaiting_payment' and checkout_mode='bank_transfer' and bank_transfer_snapshot=bank and reservation_expires_at is null) then raise exception 'TEST pending snapshot'; end if;
  if not exists(select 1 from public.payments where order_id=first_order.order_id and status='pending' and provider='bank_transfer' and paid_at is null and amount_cents=(quote->>'totalCents')::integer) then raise exception 'TEST unpaid amount'; end if;
  rejected:=false;
  begin update public.orders set bank_transfer_snapshot=bank||'{"beneficiary":"Changed"}'::jsonb where id=first_order.order_id;
  exception when others then if sqlerrm='bank_transfer_snapshot_immutable' then rejected:=true; else raise; end if; end;
  if not rejected then raise exception 'TEST snapshot mutation'; end if;
  perform set_config('request.jwt.claim.sub',admin_id::text,true);
  select updated_at into version from public.orders where id=first_order.order_id;
  execute 'set local role authenticated';
  rejected:=false;
  begin perform public.admin_save_order(first_order.order_id,version,'paid','',null,null);
  exception when others then if sqlerrm='payment_confirmation_required' then rejected:=true; else raise; end if; end;
  if not rejected then raise exception 'TEST paid without receipt reference'; end if;
  perform public.admin_save_order(first_order.order_id,version,'paid','',null,'LOCAL TEST RECEIPT');
  execute 'reset role';
  if not exists(select 1 from public.payments where order_id=first_order.order_id and status='paid' and provider_reference='LOCAL TEST RECEIPT') then raise exception 'TEST bank receipt confirmation'; end if;
  select * into other from public.create_bank_transfer_order(cart,'test@example.test','123456789',customer,address,rate,'',repeat('f',64),gen_random_uuid(),null,(quote->>'totalCents')::integer,bank);
  select updated_at into version from public.orders where id=other.order_id;
  execute 'set local role authenticated';
  perform public.admin_save_order(other.order_id,version,'cancelled','test cancellation',null,null);
  execute 'reset role';
  if (select stock_quantity from public.products where sku='TEST-01')<>before_stock-1 then raise exception 'TEST cancelled bank order stock'; end if;
end;
$$;
rollback;
