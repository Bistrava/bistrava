import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = JSON.parse(readFileSync(resolve(root, "src/lib/catalog/seo-products.generated.json"), "utf8"));
const specialist = JSON.parse(readFileSync(resolve(root, "src/lib/catalog/product-content.verified.json"), "utf8"));
const specialistIds = new Set(specialist.map((product) => product.id));
const archived = source.filter((product) => !specialistIds.has(product.id));

if (source.length !== 86 || specialistIds.size !== 24 || archived.length !== 62) {
  throw new Error("Expected 86 source products, 24 specialist drafts, and 62 archived products.");
}
if (new Set(source.map((product) => product.id)).size !== source.length ||
    new Set(source.map((product) => product.slug)).size !== source.length) {
  throw new Error("Source product IDs and slugs must be unique.");
}

function quote(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

function textArray(values) {
  return `ARRAY[${values.map(quote).join(", ")}]::text[]`;
}

const categories = new Map();
for (const product of archived) {
  const previous = categories.get(product.categorySlug);
  if (previous && previous !== product.sourceCategory) {
    throw new Error(`Conflicting category names for ${product.categorySlug}`);
  }
  categories.set(product.categorySlug, product.sourceCategory);
}

const lines = [
  "-- Generated by scripts/export-archived-catalog-sql.mjs from the preserved SEO catalog.",
  "-- The 62 imported references remain archived and are never public offers.",
  "-- Existing records are left untouched, including any later editorial edits.",
  "begin;",
  "",
];

for (const [slug, name] of categories) {
  lines.push(
    "insert into public.categories (name, slug, description, status, archived_at) " +
    `values (${quote(name)}, ${quote(slug)}, ${quote("Kategorija iz izvornega SEO kataloga; pred objavo je potreben strokovni pregled.")}, 'archived', now()) ` +
    "on conflict (slug) do nothing;",
  );
}

for (const product of archived) {
  const summary = "Arhivska kartica iz izvornega kataloga. Podatke, ceno in dobavljivost je treba preveriti pred objavo.";
  const metadata = {
    sourceCategory: product.sourceCategory,
    sourceCategorySlug: product.categorySlug,
    sourceRow: product.sourceRow,
    sourceUrl: product.researchSourceUrl,
    sourcePriority: product.priority,
    sourceSeoScore: product.seoScore,
    draftOnly: true,
  };
  const keywords = [...new Set([
    product.primaryKeyword,
    ...product.secondaryKeywords,
    ...product.longTailKeywords,
  ].filter(Boolean))];
  lines.push(
    "insert into public.products (sku, name, name_sl, slug, brand, short_description, " +
    "short_description_sl, description, description_sl, status, seo_title, seo_description, " +
    "primary_keyword, secondary_keywords, long_tail_keywords, seo_keywords, tags, " +
    "sales_mode, stock_status, stock_quantity, price_cents, merchant_data, archived_at) values (" +
    [
      quote(product.id), quote(product.name), quote(product.h1), quote(product.slug), quote(product.brand),
      quote(summary), quote(summary), quote(summary), quote(summary), "'archived'",
      quote(product.seoTitle), quote(product.sourceMetaDescription), quote(product.primaryKeyword),
      textArray(product.secondaryKeywords), textArray(product.longTailKeywords), textArray(keywords),
      textArray([product.categorySlug]), "'quote'", "'unverified'", "0", "null",
      `${quote(JSON.stringify(metadata))}::jsonb`, "now()",
    ].join(", ") +
    ") on conflict (sku) do nothing;",
  );
  lines.push(
    "insert into public.product_categories (product_id, category_id) " +
    "select p.id, c.id from public.products p cross join public.categories c " +
    `where p.sku = ${quote(product.id)} and c.slug = ${quote(product.categorySlug)} ` +
    "on conflict (product_id, category_id) do nothing;",
  );
}

lines.push("", "commit;", "");
const output = resolve(root, "supabase/seed-archived-products.sql");
writeFileSync(output, lines.join("\n"), "utf8");
console.log(`Wrote ${archived.length} archived products and ${categories.size} source categories.`);
